// Generates src/dark-theme.css — run: node scripts/gen-dark-css.mjs src/dark-theme.css
import fs from 'node:fs';

const out = [];
const esc = (c) => c.replace(/[:/.]/g, (m) => '\\' + m);
// Elements that declare their own `dark:` utility for a property opt out of the global remap.
const rule = (cls, prop, value, optOut, pseudo = '') => {
  const not = optOut ? `:not([class*="dark:${optOut}"])` : '';
  out.push(`.dark .${esc(cls)}${not}${pseudo} { ${prop}: ${value}; }`);
};

out.push(`/* ==========================================================================
   DARK THEME — auto-generated by scripts/gen-dark-css.mjs (do not edit by hand)
   Remaps the light-palette utilities used across the app when <html class="dark">.
   Any element that sets its own dark: utility for a property (e.g. dark:bg-*)
   opts out of the remap for that property, so new code can use Tailwind's
   dark: variant directly.
   ========================================================================== */`);

// ── Neutral surfaces ─────────────────────────────────────────────
const bg = {
  'white': 'var(--d-surface)',
  'white/90': 'rgb(17 26 43 / 0.9)',
  'slate-50': 'var(--d-inset)',
  'slate-50/80': 'rgb(11 18 32 / 0.8)',
  'slate-100': 'var(--d-surface-2)',
  'slate-200': 'var(--d-surface-3)',
};
for (const [k, v] of Object.entries(bg)) {
  rule(`bg-${k}`, 'background-color', v, 'bg-');
  rule(`hover:bg-${k}`, 'background-color', v, 'hover:bg-', ':hover');
}
// hover:bg-slate-50 on a white card should *lift*, not sink
rule('hover:bg-slate-50', 'background-color', 'var(--d-surface-2)', 'hover:bg-', ':hover');
rule('hover:bg-slate-50/80', 'background-color', 'var(--d-surface-2)', 'hover:bg-', ':hover');

// ── Borders / dividers ──────────────────────────────────────────
const border = {
  'white': 'var(--d-surface)',
  'slate-50': 'var(--d-border-soft)',
  'slate-100': 'var(--d-border-soft)',
  'slate-200': 'var(--d-border)',
  'slate-200/60': 'var(--d-border)',
  'slate-200/70': 'var(--d-border)',
  'slate-200/80': 'var(--d-border)',
  'slate-200/90': 'var(--d-border)',
  'slate-300': 'var(--d-border-strong)',
};
for (const [k, v] of Object.entries(border)) {
  rule(`border-${k}`, 'border-color', v, 'border-');
  rule(`hover:border-${k}`, 'border-color', v, 'hover:border-', ':hover');
}
out.push(`.dark .divide-slate-50 > :not(:last-child), .dark .divide-slate-100 > :not(:last-child) { border-color: var(--d-border-soft); }`);
out.push(`.dark .divide-slate-200 > :not(:last-child) { border-color: var(--d-border); }`);

// ── Text ────────────────────────────────────────────────────────
const text = {
  'slate-900': 'var(--d-text-1)',
  'slate-800': 'var(--d-text-2)',
  'slate-700': 'var(--d-text-3)',
  'slate-600': 'var(--d-text-4)',
  'slate-500': 'var(--d-text-5)',
};
for (const [k, v] of Object.entries(text)) {
  rule(`text-${k}`, 'color', v, 'text-');
  rule(`hover:text-${k}`, 'color', v, 'hover:text-', ':hover');
}
out.push(`.dark .placeholder-slate-400::placeholder, .dark .placeholder-slate-500::placeholder { color: var(--d-text-6); }`);

// ── Tinted (status) colours ─────────────────────────────────────
const hues = {
  emerald: ['16 185 129', '#6ee7b7'], rose: ['244 63 94', '#fda4af'],
  amber: ['245 158 11', '#fcd34d'], sky: ['14 165 233', '#7dd3fc'],
  indigo: ['99 102 241', '#a5b4fc'], violet: ['139 92 246', '#c4b5fd'],
  blue: ['59 130 246', '#93c5fd'], pink: ['236 72 153', '#f9a8d4'],
  teal: ['20 184 166', '#5eead4'], red: ['239 68 68', '#fca5a5'],
  orange: ['249 115 22', '#fdba74'], green: ['34 197 94', '#86efac'],
  purple: ['168 85 247', '#d8b4fe'], yellow: ['234 179 8', '#fde047'],
  cyan: ['6 182 212', '#67e8f9'],
};
for (const [h, [rgb, light]] of Object.entries(hues)) {
  const a = (o) => `rgb(${rgb} / ${o})`;
  for (const s of ['50', '50/40', '50/50', '50/60']) {
    rule(`bg-${h}-${s}`, 'background-color', a(0.12), 'bg-');
    rule(`hover:bg-${h}-${s}`, 'background-color', a(0.16), 'hover:bg-', ':hover');
  }
  rule(`bg-${h}-100`, 'background-color', a(0.2), 'bg-');
  rule(`hover:bg-${h}-100`, 'background-color', a(0.24), 'hover:bg-', ':hover');
  for (const s of ['100', '200', '200/80']) {
    rule(`border-${h}-${s}`, 'border-color', a(0.32), 'border-');
    rule(`hover:border-${h}-${s}`, 'border-color', a(0.45), 'hover:border-', ':hover');
  }
  for (const s of ['700', '800', '900', '950']) {
    rule(`text-${h}-${s}`, 'color', light, 'text-');
    rule(`hover:text-${h}-${s}`, 'color', light, 'hover:text-', ':hover');
  }
}

fs.writeFileSync(process.argv[2], out.join('\n') + '\n');
console.log('wrote', out.length, 'rules');
